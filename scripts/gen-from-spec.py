#!/usr/bin/env python3
"""Generate C# from the Hub specs, so the app can't drift from them.

    windows/SCREENS.md              -> src/Substratal.Hub.Core/Navigation/ScreenCatalog.g.cs   (all 75 screens)
    windows/shared/COPY-AND-STATES  -> src/Substratal.Hub.Core/Api/ErrorCopy.g.cs              (error code -> message)

Source of truth: CompositeCode/substratalapps-applications-specs. By default the files are read from GitHub (main).
Set SPECS_DIR to a local checkout of that repository to read them from disk.

    python3 scripts/gen-from-spec.py
    SPECS_DIR=../substratalapps-applications-specs python3 scripts/gen-from-spec.py

CI runs this with --check, which fails if a committed file differs from what the spec generates.
"""
import os
import re
import sys
import urllib.request

RAW = "https://raw.githubusercontent.com/CompositeCode/substratalapps-applications-specs/main/substratal-application-specs/"
CORE = os.path.join(os.path.dirname(__file__), "..", "src", "Substratal.Hub.Core")
SCREENS_OUT = os.path.join(CORE, "Navigation", "ScreenCatalog.g.cs")
COPY_OUT = os.path.join(CORE, "Api", "ErrorCopy.g.cs")


def load(rel: str) -> str:
    specs = os.environ.get("SPECS_DIR")
    if specs:
        with open(os.path.join(specs, "substratal-application-specs", *rel.split("/")), encoding="utf-8") as f:
            return f.read()
    with urllib.request.urlopen(RAW + rel, timeout=30) as r:
        return r.read().decode("utf-8")


def field(block: str, name: str) -> str:
    m = re.search(r"\*\*" + re.escape(name) + r":\*\*\s*(.+?)(?:\s+·\s+\*\*|\s*$)", block, re.M)
    return m.group(1).strip() if m else ""


def cs(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def screens() -> str:
    md = load("windows/SCREENS.md")
    parts = re.split(r"^### ", md, flags=re.M)[1:]
    rows = []
    for part in parts:
        head, _, body = part.partition("\n")
        m = re.match(r"([A-Z]{3,4}-\d{2})\s+—\s+(.+)", head.strip())
        if not m:
            continue
        sid, title = m.group(1), m.group(2).strip()
        domain = field(body, "Domain")
        rows.append({
            "id": sid,
            "title": title,
            "domain": domain.split(" ", 1)[0],
            "domain_title": domain.split(" ", 1)[1] if " " in domain else domain,
            "route": field(body, "Route").strip("`"),
            "archetype": field(body, "Archetype"),
            "phase": field(body, "Phase"),
            "who": field(body, "Who"),
            "purpose": field(body, "Purpose"),
            "container": field(body, "Windows container"),
        })
    if len(rows) < 70:
        raise SystemExit(f"Only parsed {len(rows)} screens; SCREENS.md format changed?")

    lines = [
        "// <auto-generated>",
        "// Generated by scripts/gen-screens.py from substratal-application-specs/windows/SCREENS.md.",
        "// Don't edit by hand: change the spec, then regenerate.",
        "// </auto-generated>",
        "#nullable enable",
        "namespace Substratal.Hub.Core.Navigation;",
        "",
        "public static partial class ScreenCatalog",
        "{",
        f"    /// <summary>All {len(rows)} screens the Windows app implements, in spec order.</summary>",
        "    public static readonly IReadOnlyList<Screen> All =",
        "    [",
    ]
    for r in rows:
        args = ", ".join(cs(r[k]) for k in ("id", "title", "domain", "domain_title", "route", "archetype", "phase", "who", "purpose", "container"))
        lines.append(f"        new({args}),")
    lines += ["    ];", "}", ""]
    return "\n".join(lines)


def errors() -> str:
    md = load("windows/shared/COPY-AND-STATES.md")
    section = md.split("## Error code → message", 1)[1].split("\n## ", 1)[0]
    rows = []
    for line in section.splitlines():
        m = re.match(r"\|\s*`([a-z_]+)`\s*\|\s*(\d{3})\s*\|\s*(.+?)\s*\|\s*$", line)
        if m:
            rows.append((m.group(1), int(m.group(2)), m.group(3).replace("**", "")))
    if len(rows) < 30:
        raise SystemExit(f"Only parsed {len(rows)} error codes; COPY-AND-STATES.md format changed?")
    lines = [
        "// <auto-generated>",
        "// Generated by scripts/gen-from-spec.py from substratal-application-specs/windows/shared/COPY-AND-STATES.md",
        "// (\"Error code → message\"). Don't edit by hand: change the spec, then regenerate.",
        "// </auto-generated>",
        "#nullable enable",
        "namespace Substratal.Hub.Core.Api;",
        "",
        "public static partial class ErrorCopy",
        "{",
        "    /// <summary>Spec copy per <c>error.code</c>. Placeholders: {n} seconds, {id} request id, {field}, {name}, {provider}.</summary>",
        "    static readonly Dictionary<string, (int Status, string Message)> Table = new(StringComparer.Ordinal)",
        "    {",
    ]
    for code, status, message in rows:
        lines.append(f"        [{cs(code)}] = ({status}, {cs(message)}),")
    lines += ["    };", "}", ""]
    return "\n".join(lines)


def main() -> int:
    outputs = {SCREENS_OUT: screens(), COPY_OUT: errors()}
    if "--check" in sys.argv:
        stale = []
        for path, text in outputs.items():
            with open(path, encoding="utf-8") as f:
                if f.read() != text:
                    stale.append(os.path.relpath(path))
        if stale:
            print("Out of date with the spec: " + ", ".join(stale) + ". Run scripts/gen-from-spec.py.", file=sys.stderr)
            return 1
        print("Generated files match the spec.")
        return 0
    for path, text in outputs.items():
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        print(f"Wrote {os.path.relpath(path)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
